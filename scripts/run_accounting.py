"""Run accounting: items, refusals, parse failures and floor share per cell and per model column,
plus rows in the replicate, temp0 and userfold files. Other tagged files are listed separately.
Reads data/results/ and writes docs/RUN_ACCOUNTING.md.

    python scripts/run_accounting.py
    python scripts/run_accounting.py --spend spend.yaml     # adds the provider totals read
                                                            # off each console (see the template)

spend.yaml template (one total per provider):
    openai: {usd: 0, note: "gpt-5.6-sol + persuadee + judge"}
    anthropic: {usd: 0, note: "claude-fable-5.1 + second judge (haiku)"}
    deepseek: {usd: 0}
    moonshot: {usd: 0}
    mistral: {usd: 0}
"""
import argparse, json, sys
from collections import defaultdict
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from core import registry  # noqa: E402

RESULTS = registry.ROOT / "data" / "results"
STUDY_TAGS = {"rep2": "replicate", "temp0": "temperature-0 check",
              "userfold": "packaging check"}


def read(path):
    ids, ref, bad = {}, 0, 0
    for line in open(path, encoding="utf-8"):
        try:
            r = json.loads(line)
        except json.JSONDecodeError:
            continue
        if "item_id" not in r or r["item_id"] in ids:
            continue
        ids[r["item_id"]] = 1
        ref += bool(r.get("refused")); bad += not r.get("parse_ok", True)
    return len(ids), ref, bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spend")
    a = ap.parse_args()
    cfg = registry.load()
    methods = [m for m, mc in cfg["methods"].items() if isinstance(mc.get("n"), int)]
    models = list(registry.all_models(cfg))
    cells, col, other = {}, defaultdict(lambda: defaultdict(int)), defaultdict(list)
    for m in methods:
        for f in sorted((RESULTS / m).glob("*.jsonl")):
            stem = f.stem
            model, _, tag = stem.partition("__")
            if model not in models:
                continue
            n, ref, bad = read(f)
            if not tag:
                cells[(m, model)] = (n, ref, bad)
                col[model]["items"] += n; col[model]["refused"] += ref; col[model]["unparsed"] += bad
            elif tag in STUDY_TAGS:
                col[model][tag] += n
            else:
                other[tag].append(f"{m}/{stem}")
    out = ["# Run accounting", "",
           f"Generated by `scripts/run_accounting.py` from `data/results/`. Methods: {len(methods)}; "
           f"models: {len(models)}; cells with a main file: {len(cells)} of {len(methods) * len(models)}.",
           "Items are distinct `item_id`s (ju2025 counts strategy rows, 11 per CounterFact item). "
           "Refused and unparsed items carry `score: null` and enter the primary analysis at the "
           "method's floor.", "",
           "## Per model column", "",
           "| Model | Items | Refused | Unparsed | Floor share | Replicate rows | temp0 | userfold |",
           "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for model in models:
        c = col[model]
        floor = (c["refused"] + c["unparsed"]) / c["items"] if c["items"] else 0
        out.append(f"| {model} | {c['items']} | {c['refused']} | {c['unparsed']} | {floor:.1%} | "
                   f"{c['rep2']} | {c['temp0']} | {c['userfold']} |")
    out += ["", "## Per cell: items / refused / unparsed", "",
            "| Method | " + " | ".join(models) + " |", "| --- |" + " ---: |" * len(models)]
    for m in methods:
        row = []
        for model in models:
            v = cells.get((m, model))
            row.append("—" if v is None else (f"{v[0]}" if v[1] == v[2] == 0 else f"{v[0]} / {v[1]} / {v[2]}"))
        out.append(f"| {m} (n={cfg['methods'][m]['n']}) | " + " | ".join(row) + " |")
    if other:
        out += ["", "## Tagged files that are NOT study data", ""]
        for tag, files in sorted(other.items()):
            out.append(f"- `{tag}` ({len(files)}): " + ", ".join(files[:6]) + (" …" if len(files) > 6 else ""))
    if a.spend:
        sp = yaml.safe_load(open(a.spend))
        out += ["", "## Spend per provider (from the provider consoles)", "",
                "| Provider | USD | Covers |", "| --- | ---: | --- |"]
        out += [f"| {p} | {v.get('usd', 0):.0f} | {v.get('note', '')} |" for p, v in sp.items()]
        out.append(f"| **total** | **{sum(v.get('usd', 0) for v in sp.values()):.0f}** | |")
    dest = registry.ROOT / "docs" / "RUN_ACCOUNTING.md"
    dest.parent.mkdir(exist_ok=True)
    dest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out[:16]))
    print(f"... -> {dest}")


if __name__ == "__main__":
    main()
